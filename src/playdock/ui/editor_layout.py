"""PlayDock TitleEditor Qt widget tree/layout.

Event handlers and application state remain owned by title_editor.py.
"""

from PySide6.QtCore import Qt
from PySide6.QtWidgets import (
    QWidget, QLabel, QLineEdit, QPushButton, QHBoxLayout, QVBoxLayout,
    QListWidget, QFrame, QSplitter, QStackedWidget, QScrollArea,
)
from services.localized_titles import LANGUAGES
from ui.selectors import DarkMenuSelect


def build_title_editor_ui(self):
    root = QWidget()
    self.setCentralWidget(root)
    layout = QVBoxLayout(root)
    layout.setContentsMargins(0, 0, 0, 0)
    layout.setSpacing(0)
    header = QFrame()
    header.setObjectName('Header')
    top = QHBoxLayout(header)
    top.setContentsMargins(18, 13, 18, 13)
    title = QLabel('게임 이름 관리자')
    title.setObjectName('Heading')
    top.addWidget(title)
    self.mode_btn = QPushButton('상세 기능 보기')
    self.mode_btn.setToolTip('기존 품번 조회, 번역, 언어별 제목 관리 화면으로 전환')
    self.mode_btn.clicked.connect(self.toggle_mode)
    top.addWidget(self.mode_btn)
    top.addStretch()
    self.language_header = QLabel('표시 언어')
    top.addWidget(self.language_header)
    self.language_menu = DarkMenuSelect()
    for language, (label, _locale) in LANGUAGES.items():
        self.language_menu.addItem(label, language)
    initial_lang = self.library.settings.get('title_language', 'ko')
    pos = self.language_menu.findData(initial_lang)
    self.language_menu.setCurrentIndex(pos if pos >= 0 else 0)
    self.language_menu.currentIndexChanged.connect(self.change_language)
    top.addWidget(self.language_menu)
    self.bulk_settings_btn = QPushButton('일괄 이름 변경 · 상세 설정')
    self.bulk_settings_btn.clicked.connect(self.open_bulk_settings)
    top.addWidget(self.bulk_settings_btn)
    self.bulk_btn = QPushButton('품번만 있는 게임 일괄 조회')
    self.bulk_btn.clicked.connect(self.bulk_lookup)
    refresh_btn = QPushButton('게임 목록 새로고침')
    refresh_btn.clicked.connect(self.refresh)
    top.addWidget(refresh_btn)
    # Keep the simplified mode clean; advanced controls remain available.
    self.language_header.hide()
    self.language_menu.hide()
    self.bulk_btn.hide()
    layout.addWidget(header)

    splitter = QSplitter(Qt.Orientation.Horizontal)
    layout.addWidget(splitter, 1)
    left = QWidget()
    side = QVBoxLayout(left)
    side.setContentsMargins(14, 15, 10, 15)
    side.setSpacing(9)
    side.addWidget(QLabel('로컬 게임 목록'))
    self.search = QLineEdit()
    self.search.setPlaceholderText('게임 이름 또는 RJ 품번 검색')
    self.search.setClearButtonEnabled(True)
    self.search.textChanged.connect(self.populate)
    side.addWidget(self.search)
    self.games_list = QListWidget()
    # Titles can be far longer than the sidebar. Keep one row per game and
    # show a trailing ellipsis instead of exposing Qt's tiny bottom bar.
    # The full selected title remains visible in the detail panel.
    self.games_list.setHorizontalScrollBarPolicy(Qt.ScrollBarPolicy.ScrollBarAlwaysOff)
    self.games_list.setTextElideMode(Qt.TextElideMode.ElideRight)
    self.games_list.setWordWrap(False)
    self.games_list.currentItemChanged.connect(self.select_game)
    side.addWidget(self.games_list, 1)
    self.count = QLabel('')
    self.count.setObjectName('Muted')
    side.addWidget(self.count)
    splitter.addWidget(left)

    main = QWidget()
    content = QVBoxLayout(main)
    content.setContentsMargins(18, 18, 18, 18)
    content.setSpacing(12)
    # The new default page is deliberately small; the original editor
    # remains intact as the second page, selected by the header button.
    self.panel_stack = QStackedWidget()
    simple_page = QWidget()
    simple_layout = QVBoxLayout(simple_page)
    simple_layout.setContentsMargins(0, 0, 0, 0)
    simple_layout.setSpacing(10)
    simple_card = QFrame()
    simple_card.setObjectName('SimplePanel')
    simple = QVBoxLayout(simple_card)
    simple.setContentsMargins(20, 20, 20, 20)
    simple.setSpacing(12)
    simple_heading = QLabel('간편 이름 수정')
    simple_heading.setObjectName('Heading')
    simple.addWidget(simple_heading)
    simple_description = QLabel('왼쪽 게임 목록에서 선택 → 새 이름 입력 → 저장.\n'
                                '원본 게임 파일·모음집·설정은 변경하지 않습니다.')
    simple_description.setObjectName('Muted')
    simple_description.setWordWrap(True)
    simple.addWidget(simple_description)
    simple.addWidget(QLabel('현재 라이브러리에 표시되는 이름'))
    self.simple_current = QLabel('왼쪽에서 게임을 선택하세요')
    self.simple_current.setObjectName('SimpleValue')
    self.simple_current.setWordWrap(True)
    simple.addWidget(self.simple_current)
    simple.addWidget(QLabel('새 이름'))
    self.simple_edit = QLineEdit()
    self.simple_edit.setPlaceholderText('여기에 원하는 게임 이름을 입력하세요')
    self.simple_edit.returnPressed.connect(self.save_simple_title)
    self.simple_edit.textChanged.connect(self.simple_preview_changed)
    simple.addWidget(self.simple_edit)
    self.simple_preview = QLabel('')
    self.simple_preview.setObjectName('Muted')
    self.simple_preview.setWordWrap(True)
    simple.addWidget(self.simple_preview)
    self.simple_korean_btn = QPushButton('한국어 제목 웹 검색 (무료 · 번역 아님)')
    self.simple_korean_btn.clicked.connect(self.open_korean_lookup_from_simple)
    simple.addWidget(self.simple_korean_btn)
    save_row = QHBoxLayout()
    save_row.addStretch(1)
    self.simple_save_btn = QPushButton('이 이름으로 저장')
    self.simple_save_btn.setObjectName('Save')
    self.simple_save_btn.clicked.connect(self.save_simple_title)
    save_row.addWidget(self.simple_save_btn)
    simple.addLayout(save_row)
    line = QFrame()
    line.setFrameShape(QFrame.Shape.HLine)
    line.setStyleSheet('background:#354b5d; max-height:1px; border:none;')
    simple.addWidget(line)
    simple.addWidget(QLabel('되돌리기'))
    self.history_label = QLabel('저장된 이전 이름이 없습니다.')
    self.history_label.setObjectName('Muted')
    self.history_label.setWordWrap(True)
    simple.addWidget(self.history_label)
    history_row = QHBoxLayout()
    self.simple_undo_btn = QPushButton('이전 이름으로 되돌리기')
    self.simple_undo_btn.clicked.connect(self.undo_simple_title)
    history_row.addWidget(self.simple_undo_btn)
    self.simple_original_btn = QPushButton('원본 파일명으로 복원')
    self.simple_original_btn.clicked.connect(self.restore_simple_original)
    history_row.addWidget(self.simple_original_btn)
    simple.addLayout(history_row)
    original_hint = QLabel('이전 이름은 게임별로 저장되므로 프로그램을 다시 열어도 복원할 수 있습니다.\n'
                           '원본 파일명으로 복원한 뒤에도 다시 이전 이름으로 되돌릴 수 있습니다.')
    original_hint.setWordWrap(True)
    original_hint.setObjectName('Muted')
    simple.addWidget(original_hint)
    simple_layout.addWidget(simple_card)
    simple_layout.addStretch(1)
    self.panel_stack.addWidget(simple_page)

    # Keep the previous detailed title editor with all lookup/language tools.
    section = QFrame()
    section.setObjectName('Panel')
    block = QVBoxLayout(section)
    block.setContentsMargins(16, 14, 16, 14)
    block.setSpacing(11)
    block.addWidget(self.bulk_btn)
    hint = QLabel('원본 ZIP·7z 및 설치 폴더는 변경하지 않고 라이브러리에 표시되는 이름만 저장합니다.')
    hint.setObjectName('Muted')
    hint.setWordWrap(True)
    block.addWidget(hint)
    block.addWidget(QLabel('현재 게임 이름'))
    self.original = QLabel('게임을 선택하세요')
    self.original.setWordWrap(True)
    block.addWidget(self.original)
    self.file_detail = QLabel('')
    self.file_detail.setObjectName('Muted')
    self.file_detail.setWordWrap(True)
    block.addWidget(self.file_detail)
    override_row = QHBoxLayout()
    override_row.addWidget(QLabel('이 게임의 표시 언어'))
    self.game_language_menu = DarkMenuSelect()
    self.game_language_menu.addItem('기본 설정 따름', '')
    for language, (label, _locale) in LANGUAGES.items():
        self.game_language_menu.addItem(label, language)
    override_row.addWidget(self.game_language_menu)
    self.game_language_save = QPushButton('게임별 언어 저장')
    self.game_language_save.clicked.connect(self.save_game_language)
    override_row.addWidget(self.game_language_save)
    block.addLayout(override_row)
    block.addWidget(QLabel('언어별 작품 제목 (원본 파일명과 별도 관리)'))
    self.localized_edit = QLineEdit()
    self.localized_edit.setPlaceholderText('한국어 제목을 조회하거나 직접 입력하세요')
    self.localized_edit.textEdited.connect(self.localized_manually_edited)
    block.addWidget(self.localized_edit)
    locale_controls = QHBoxLayout()
    self.localized_lookup_btn = QPushButton('품번으로 선택 언어 제목 조회')
    self.localized_lookup_btn.clicked.connect(lambda: self.start_lookup('localized'))
    locale_controls.addWidget(self.localized_lookup_btn)
    self.translate_btn = QPushButton('AI로 번역 (선택)')
    self.translate_btn.clicked.connect(lambda: self.start_lookup('translate'))
    locale_controls.addWidget(self.translate_btn)
    self.localized_save_btn = QPushButton('이 언어의 제목 저장')
    self.localized_save_btn.clicked.connect(self.save_localized_title)
    locale_controls.addWidget(self.localized_save_btn)
    block.addLayout(locale_controls)
    korean_web_row = QHBoxLayout()
    self.korean_web_btn = QPushButton('한국어 제목 웹 검색 (무료 · 번역 아님)')
    self.korean_web_btn.clicked.connect(lambda: self.start_lookup('korean_web'))
    korean_web_row.addWidget(self.korean_web_btn)
    self.korean_browser_btn = QPushButton('브라우저에서 한국어 제목 검색')
    self.korean_browser_btn.clicked.connect(self.open_korean_title_search)
    korean_web_row.addWidget(self.korean_browser_btn)
    korean_web_row.addStretch(1)
    block.addLayout(korean_web_row)
    block.addWidget(QLabel('수동 표시 이름 (언어별 제목이 없을 때 사용)'))
    self.edit = QLineEdit()
    self.edit.setPlaceholderText('수동으로 수정하거나 아래 버튼에서 후보를 조회하세요')
    block.addWidget(self.edit)
    block.addWidget(QLabel('작품 코드 (선택 사항 · 없어도 등록 가능)'))
    code_row = QHBoxLayout()
    self.code_input = QLineEdit()
    self.code_input.setPlaceholderText('RJ01081508 · 품번이 없는 게임은 빈칸')
    self.code_input.textChanged.connect(lambda _value: self.set_enabled(self.current_game() is not None))
    code_row.addWidget(self.code_input, 1)
    self.code_save_btn = QPushButton('품번만 저장')
    self.code_save_btn.clicked.connect(self.save_code)
    code_row.addWidget(self.code_save_btn)
    block.addLayout(code_row)
    row = QHBoxLayout()
    self.lookup_btn = QPushButton('RJ 품번으로 제목 조회')
    self.lookup_btn.clicked.connect(lambda: self.start_lookup('rj'))
    row.addWidget(self.lookup_btn)
    self.gpt_btn = QPushButton('AI로 이름 추천 (서비스별 요금 가능)')
    self.gpt_btn.clicked.connect(lambda: self.start_lookup('gpt'))
    row.addWidget(self.gpt_btn)
    block.addLayout(row)
    self.source = QLabel('조회한 제목은 확인 후 적용해 주세요.')
    self.source.setObjectName('Muted')
    self.source.setWordWrap(True)
    block.addWidget(self.source)
    controls = QHBoxLayout()
    self.reset_btn = QPushButton('원본 파일명으로 복원')
    self.reset_btn.clicked.connect(self.reset_title)
    controls.addWidget(self.reset_btn)
    controls.addStretch()
    self.save_btn = QPushButton('표시 이름 저장')
    self.save_btn.setObjectName('Save')
    self.save_btn.clicked.connect(self.save_title)
    controls.addWidget(self.save_btn)
    block.addLayout(controls)
    detailed_page = QScrollArea()
    detailed_page.setWidgetResizable(True)
    detailed_page.setFrameShape(QFrame.Shape.NoFrame)
    detailed_page.setHorizontalScrollBarPolicy(Qt.ScrollBarPolicy.ScrollBarAlwaysOff)
    detailed_inner = QWidget()
    detailed_layout = QVBoxLayout(detailed_inner)
    detailed_layout.setContentsMargins(0, 0, 0, 0)
    detailed_layout.addWidget(section)
    detailed_layout.addStretch(1)
    detailed_page.setWidget(detailed_inner)
    self.panel_stack.addWidget(detailed_page)
    content.addWidget(self.panel_stack, 1)
    self.panel_stack.setCurrentIndex(0)
    self.status = QLabel('기존 게임을 안전하게 유지합니다. 저장한 이름은 본체에서 새로고침하면 반영됩니다.')
    self.status.setObjectName('Muted')
    self.status.setWordWrap(True)
    content.addWidget(self.status)
    content.addStretch()
    splitter.addWidget(main)
    splitter.setSizes([345, 735])
    self.set_enabled(False)
